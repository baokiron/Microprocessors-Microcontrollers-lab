// Task one-shot (tat): tat LED D6, chay dung 1 lan
void TaskOneShotOff(void) {
	HAL_GPIO_WritePin(one_shot_GPIO_Port, one_shot_Pin, GPIO_PIN_RESET);
	printTime("one_shot OFF");
}

// Task one-shot (bat): bat LED D6 roi hen gio 1 s sau tat LED (one-shot thu hai)
void TaskOneShot(void) {
	HAL_GPIO_WritePin(one_shot_GPIO_Port, one_shot_Pin, GPIO_PIN_SET);
	printTime("one_shot ON");
	SCH_Add_Task(TaskOneShotOff, MS_TO_TICKS(1000), 0);
}
