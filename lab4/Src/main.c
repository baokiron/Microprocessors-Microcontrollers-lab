// In "[thoi_gian ms] ten_task" ra UART (Virtual Terminal trong Proteus)
static void printTime(const char *name) {
	char buf[40];
	int n = snprintf(buf, sizeof(buf), "[%lu ms] %s\r\n",
			(unsigned long) get_time(), name);
	if (n > 0)
		HAL_UART_Transmit(&huart1, (uint8_t*) buf, (uint16_t) n, 50);
}

void Task1(void) { HAL_GPIO_TogglePin(task1_GPIO_Port, task1_Pin); printTime("task1"); } // 0.5 s
void Task2(void) { HAL_GPIO_TogglePin(task2_GPIO_Port, task2_Pin); printTime("task2"); } // 1.0 s
void Task3(void) { HAL_GPIO_TogglePin(task3_GPIO_Port, task3_Pin); printTime("task3"); } // 1.5 s
void Task4(void) { HAL_GPIO_TogglePin(task4_GPIO_Port, task4_Pin); printTime("task4"); } // 2.0 s
